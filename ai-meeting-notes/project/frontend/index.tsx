function MeetingNotesApp() {
    const {customPropertyValueByKey} = useCustomProperties(getCustomProperties);

    const meetingsTable = customPropertyValueByKey.meetingsTable;
    const projectsTable = customPropertyValueByKey.projectsTable;
    const actionItemsTable = customPropertyValueByKey.actionItemsTable;
    const teamMembersTable = customPropertyValueByKey.teamMembersTable;
    const notesField = customPropertyValueByKey.notesField;
    const agendaField = customPropertyValueByKey.agendaField;
    const decisionsField = customPropertyValueByKey.decisionsField;
    const aiSummaryField = customPropertyValueByKey.aiSummaryField;
    const projectAiSummaryField = customPropertyValueByKey.projectAiSummaryField;

    // Validate that projectAiSummaryField belongs to projectsTable, not meetingsTable
    const validProjectAiSummaryField = projectAiSummaryField && projectsTable && 
        projectsTable.fields.find((f: AT) => f.id === projectAiSummaryField.id) ? projectAiSummaryField : null;
    const attendeesField = customPropertyValueByKey.attendeesField;
    const extractActionItemsField = customPropertyValueByKey.extractActionItemsField;
    const sendFollowUpField = customPropertyValueByKey.sendFollowUpField;

    if (!meetingsTable || !projectsTable || !actionItemsTable || !notesField) {
        return (
            <div className="min-h-screen bg-gray-gray25 dark:bg-gray-gray800">
                <div className="h-[3px] bg-gray-gray200 dark:bg-gray-gray600" />
                <div className="flex items-center justify-center" style={{minHeight: 'calc(100vh - 3px)'}}>
                    <div className="text-center max-w-xs px-4">
                        <div className="w-14 h-14 rounded-xl bg-gray-gray200 dark:bg-gray-gray600 flex items-center justify-center mx-auto mb-5">
                            <NotepadIcon size={20} className="text-gray-gray500 dark:text-gray-gray400" />
                        </div>
                        <h2 className="text-xl font-display font-bold text-gray-gray700 dark:text-gray-gray200 mb-2">
                            Meeting Notes
                        </h2>
                        <p className="text-[11px] text-gray-gray400 dark:text-gray-gray500 leading-relaxed">
                            Open the properties panel to configure your tables and fields.
                        </p>
                    </div>
                </div>
            </div>
        );
    }

    return (
        <MeetingNotesInner
            meetingsTable={meetingsTable}
            projectsTable={projectsTable}
            actionItemsTable={actionItemsTable}
            teamMembersTable={teamMembersTable}
            notesField={notesField}
            agendaField={agendaField}
            decisionsField={decisionsField}
            aiSummaryField={aiSummaryField}
            projectAiSummaryField={validProjectAiSummaryField}
            attendeesField={attendeesField}
            extractActionItemsField={extractActionItemsField}
            sendFollowUpField={sendFollowUpField}
        />
    );
}

function MeetingNotesInner({meetingsTable, projectsTable, actionItemsTable, teamMembersTable, notesField, agendaField, decisionsField, aiSummaryField, projectAiSummaryField, attendeesField, extractActionItemsField, sendFollowUpField}: {
    meetingsTable: AT; projectsTable: AT; actionItemsTable: AT; teamMembersTable: AT;
    notesField: AT; agendaField: AT; decisionsField: AT; aiSummaryField: AT; projectAiSummaryField: AT; attendeesField: AT;
    extractActionItemsField: AT; sendFollowUpField: AT;
}) {
    const projects = useRecords(projectsTable);
    const meetings = useRecords(meetingsTable);
    const actionItems = useRecords(actionItemsTable);
    const teamMembers = useRecords(teamMembersTable ?? projectsTable);
    const actualTeamMembers = teamMembersTable ? teamMembers : [];

    const [selectedProjectId, setSelectedProjectId] = useState<string | null>(null);
    const [selectedMeetingId, setSelectedMeetingId] = useState<string | null>(null);

    const projectLinkField = useMemo(() =>
        meetingsTable.fields.find((f: AT) =>
            f.config.type === FieldType.MULTIPLE_RECORD_LINKS &&
            f.config.options?.linkedTableId === projectsTable.id,
        ) ?? null,
        [meetingsTable, projectsTable]);

    const meetingLinkField = useMemo(() =>
        actionItemsTable.fields.find((f: AT) =>
            f.config.type === FieldType.MULTIPLE_RECORD_LINKS &&
            f.config.options?.linkedTableId === meetingsTable.id,
        ) ?? null,
        [actionItemsTable, meetingsTable]);

    const selectedMeeting = meetings.find((m: AT) => m.id === selectedMeetingId);

    if (selectedMeetingId && !selectedMeeting) {
        return (
            <div className="min-h-screen bg-gray-gray25 dark:bg-gray-gray800">
                <div className="h-[3px] bg-gray-gray200 dark:bg-gray-gray600" />
                <div className="flex items-center justify-center" style={{minHeight: 'calc(100vh - 3px)'}}>
                    <div className="flex items-center gap-2">
                        <span className="w-1.5 h-1.5 rounded-full bg-blue-blue animate-pulse" />
                        <span className="text-[11px] text-gray-gray400">Loading...</span>
                    </div>
                </div>
            </div>
        );
    }

    if (selectedMeeting) {
        return (
            <MeetingWorkspace
                meeting={selectedMeeting}
                meetingsTable={meetingsTable}
                actionItemsTable={actionItemsTable}
                actionItems={actionItems}
                notesField={notesField}
                agendaField={agendaField}
                decisionsField={decisionsField}
                aiSummaryField={aiSummaryField}
                attendeesField={attendeesField}
                extractActionItemsField={extractActionItemsField}
                sendFollowUpField={sendFollowUpField}
                meetingLinkField={meetingLinkField}
                teamMembers={actualTeamMembers}
                onBack={() => setSelectedMeetingId(null)}
            />
        );
    }

    if (selectedProjectId) {
        return (
            <MeetingSelector
                projects={projects}
                meetings={meetings}
                meetingsTable={meetingsTable}
                projectLinkField={projectLinkField}
                actionItems={actionItems}
                meetingLinkField={meetingLinkField}
                notesField={notesField}
                agendaField={agendaField}
                aiSummaryField={aiSummaryField}
                attendeesField={attendeesField}
                teamMembers={actualTeamMembers}
                selectedProjectId={selectedProjectId}
                setSelectedProjectId={setSelectedProjectId}
                onSelectMeeting={setSelectedMeetingId}
            />
        );
    }

    const aiStatusField = actionItemsTable.fields.find((f: AT) =>
        f.config.type === FieldType.SINGLE_SELECT && f.name.toLowerCase().includes('status'),
    );

    return (
        <ProjectsHome
            projects={projects}
            projectsTable={projectsTable}
            meetings={meetings}
            actionItems={actionItems}
            projectLinkField={projectLinkField}
            meetingLinkField={meetingLinkField}
            aiStatusField={aiStatusField}
            projectAiSummaryField={projectAiSummaryField}
            onSelectProject={setSelectedProjectId}
        />
    );
}

initializeBlock({interface: () => <MeetingNotesApp />});
