// ─── Inline Markdown Parser (replaces 'marked') ────────────────
const markdownParse = (md: string): string => {
    const codeBlocks: string[] = [];
    let processed = md.replace(/```([\s\S]*?)```/g, (_match, code) => {
        const escaped = code.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
        codeBlocks.push('<pre><code>' + escaped.trim() + '</code></pre>');
        return '\x00CB' + (codeBlocks.length - 1) + '\x00';
    });
    let html = processed
        .replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;')
        .replace(/^### (.+)$/gm, '<h3>$1</h3>')
        .replace(/^## (.+)$/gm, '<h2>$1</h2>')
        .replace(/^# (.+)$/gm, '<h1>$1</h1>')
        .replace(/\*\*\*(.+?)\*\*\*/g, '<strong><em>$1</em></strong>')
        .replace(/\*\*(.+?)\*\*/g, '<strong>$1</strong>')
        .replace(/\*(.+?)\*/g, '<em>$1</em>')
        .replace(/`([^`]+)`/g, '<code>$1</code>')
        .replace(/\[([^\]]+)\]\(([^)]+)\)/g, (_m, text: string, url: string) => {
            const safeUrl = url.trim().toLowerCase().startsWith('javascript:') ? '#' : url;
            return '<a href="' + safeUrl + '">' + text + '</a>';
        })
        .replace(/^---$/gm, '<hr>')
        .replace(/\n/g, '<br>');
    html = html.replace(/((?:^[-*]\s.+<br>?)+)/gm, (match) => {
        const items = match.split('<br>').filter(Boolean).map(l => l.replace(/^[-*]\s/, ''));
        return '<ul>' + items.map(i => '<li>' + i + '</li>').join('') + '</ul>';
    });
    html = html.replace(/((?:^\d+\.\s.+<br>?)+)/gm, (match) => {
        const items = match.split('<br>').filter(Boolean).map(l => l.replace(/^\d+\.\s/, ''));
        return '<ol>' + items.map(i => '<li>' + i + '</li>').join('') + '</ol>';
    });
    html = html.replace(/\x00CB(\d+)\x00/g, (_m, idx) => codeBlocks[parseInt(idx)]);
    return html;
};

