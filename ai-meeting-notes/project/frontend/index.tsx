function sanitize(container: HTMLElement) {
    container.querySelectorAll('script, iframe, object, embed, form').forEach(el => el.remove());
    container.querySelectorAll('*').forEach(el => {
        for (const attr of Array.from(el.attributes)) {
            if (attr.name.startsWith('on') || attr.value.trim().toLowerCase().startsWith('javascript:')) {
                el.removeAttribute(attr.name);
            }
        }
    });
}

function safeSetHtml(el: HTMLElement, html: string) {
    const parser = new DOMParser();
    const doc = parser.parseFromString(html, 'text/html');
    sanitize(doc.body);
    el.replaceChildren(...Array.from(doc.body.childNodes).map(n => n.cloneNode(true)));
}

function nodeToMd(node: Node, listDepth = 0): string {
    if (node.nodeType === Node.TEXT_NODE) return node.textContent ?? '';
    if (node.nodeType !== Node.ELEMENT_NODE) return '';
    const el = node as HTMLElement;
    const tag = el.tagName.toLowerCase();
    const inner = Array.from(el.childNodes).map(c => nodeToMd(c, listDepth)).join('');

    switch (tag) {
        case 'strong': case 'b': return `**${inner}**`;
        case 'em': case 'i': return `*${inner}*`;
        case 's': case 'strike': case 'del': return `~~${inner}~~`;
        case 'u': return `<u>${inner}</u>`;
        case 'sub': return `<sub>${inner}</sub>`;
        case 'sup': return `<sup>${inner}</sup>`;
        case 'h1': return `# ${inner}\n\n`;
        case 'h2': return `## ${inner}\n\n`;
        case 'h3': return `### ${inner}\n\n`;
        case 'p': return `${inner}\n\n`;
        case 'br': return '\n';
        case 'ul': case 'ol':
            return Array.from(el.childNodes).map(c => nodeToMd(c, listDepth + 1)).join('') + (listDepth === 0 ? '\n' : '');
        case 'li': {
            const p = el.parentElement;
            const indent = '   '.repeat(Math.max(0, listDepth - 1));
            let text = '';
            let nested = '';
            for (const child of Array.from(el.childNodes)) {
                if (child.nodeType === Node.ELEMENT_NODE) {
                    const ct = (child as HTMLElement).tagName.toLowerCase();
                    if (ct === 'ul' || ct === 'ol') {
                        nested += nodeToMd(child, listDepth);
                        continue;
                    }
                }
                text += nodeToMd(child, listDepth);
            }
            const marker = p?.tagName.toLowerCase() === 'ol'
                ? `${Array.from(p.children).indexOf(el) + 1}. `
                : '- ';
            return `${indent}${marker}${text.trim()}\n${nested}`;
        }
        case 'blockquote':
            return inner.split('\n').filter(l => l.trim()).map(l => `> ${l}`).join('\n') + '\n\n';
        case 'code':
            return el.parentElement?.tagName.toLowerCase() === 'pre' ? inner : `\`${inner}\``;
        case 'pre': return `\`\`\`\n${inner}\n\`\`\`\n\n`;
        case 'a': return `[${inner}](${el.getAttribute('href') ?? ''})`;
        case 'hr': return '---\n\n';
        case 'div': return `${inner}\n`;
        default: return inner;
    }
}

function domToMarkdown(el: HTMLElement): string {
    return nodeToMd(el).replace(/\n{3,}/g, '\n\n').trim();
}

